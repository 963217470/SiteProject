    await page.getByRole('button',{name:'重做',exact:true}).click()
    await page.locator('.map-meta').filter({hasText:'7 个节点'}).waitFor()
    await page.locator('.map-canvas .smm-node').filter({hasText:'分支主题'}).click()
    await page.getByRole('button',{name:'删除节点',exact:true}).click()
    await page.locator('.map-meta').filter({hasText:'6 个节点'}).waitFor()
    await page.getByRole('button',{name:'撤销',exact:true}).click()
    await page.locator('.map-meta').filter({hasText:'7 个节点'}).waitFor()
