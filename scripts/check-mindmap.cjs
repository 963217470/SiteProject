    assert.equal(await page.getByLabel('Markdown 正文',{exact:true}).inputValue(),original)
    assert.ok(!popup.url().includes('?id='))
    await popup.close()
    const guest=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
    guest.on('pageerror',e=>errors.push(e.message))
    await guest.goto(savedURL,{waitUntil:'networkidle'})
    await guest.locator('.map-message.error').filter({hasText:'登录'}).waitFor()
    assert.equal(await guest.getByRole('button',{name:'保存草稿',exact:true}).isDisabled(),true)
    await guest.goto(base+'/mindmap/',{waitUntil:'networkidle'})
    await guest.locator('.map-canvas .smm-node').first().waitFor()
    await guest.getByRole('button',{name:'适应画布',exact:true}).click()
    await guest.locator('.map-canvas .smm-node').filter({hasText:'我的游戏创意'}).tap()
    await guest.getByLabel('节点标题',{exact:true}).waitFor()
    await guest.getByRole('button',{name:'关闭节点面板',exact:true}).click()
