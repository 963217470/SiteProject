    await page.locator('.map-meta').filter({hasText:'本机工作区'}).waitFor()
    assert.equal(await page.locator('.map-canvas .smm-node').count(),6)
    const visible=await page.locator('.map-canvas svg text').first().evaluate(e=>{const n=e.getBoundingClientRect(),c=e.closest('.map-canvas').getBoundingClientRect();return n.width>0&&n.x>=c.x&&n.right<=c.right&&n.y>=c.y&&n.bottom<=c.bottom})
    assert.equal(visible,true)
    await page.locator('.map-canvas .smm-node').filter({hasText:'核心玩法'}).click()
    await page.getByLabel('节点标题',{exact:true}).fill('核心循环')
    await page.getByLabel('节点 Markdown 笔记').fill('# 节点笔记\n\n$$E=mc^2$$\n\n```js\nconst score = 1\n```\n\n![图片](/images/default-cover.svg)')
