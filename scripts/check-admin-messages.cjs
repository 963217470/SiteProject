const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const base=process.env.RD_UI_TEST_URL||'http://127.0.0.1:5193'
assert.equal(new URL(base).hostname,'127.0.0.1')
async function api(page,path,method='GET',body){const r=await page.request.fetch(base+'/api'+path,{method,headers:{'X-RD-CSRF':'1'},...(body?{data:body}:{})});assert.ok(r.ok(),await r.text());return r.json()}
async function main(){
 const b=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']})
 try{
  const admin=await b.newPage({viewport:{width:1440,height:1000}}),member=await b.newPage({viewport:{width:1440,height:1000}}),guest=await b.newPage()
  const errors=[];for(const p of [admin,member,guest])p.on('pageerror',e=>errors.push(e.message))
  await member.goto(base+'/api/__preview/member');const owner=(await api(member,'/auth/session')).session.user.id
  const title='管理审核浏览器测试 '+Date.now(),noticeTitle='浏览器通知验证 '+Date.now()
  const article=(await api(member,'/data/articles','POST',{title,content:'# 原文'}))[0]
  await api(member,'/data/profile_changes','POST',{username:'预览社员',bio:'等待审核的新资料'})
  await api(member,'/data/knowledge_branch_requests','POST',{article_id:article.id,requested_path:'浏览器审核分支',requested_description:'审核测试说明'})
  await admin.goto(base+'/api/__preview/admin');await admin.goto(base+'/admin/')
  await admin.getByRole('heading',{name:'管理后台',exact:true}).waitFor()
  await admin.getByText(title,{exact:true}).waitFor()
  assert.equal(await admin.locator('.admin-sidebar a').count(),8)
  await admin.screenshot({path:'artifacts/admin-hub-desktop.png',fullPage:true})
  await admin.setViewportSize({width:390,height:844});assert.ok(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await admin.screenshot({path:'artifacts/admin-hub-mobile.png',fullPage:true})
  await admin.setViewportSize({width:1440,height:1000})
  await admin.getByRole('button',{name:'发送通知',exact:true}).click()
  await admin.getByLabel('通知标题',{exact:true}).fill(noticeTitle)
  await admin.getByLabel('通知内容',{exact:true}).fill('这是一条仅发给指定测试用户的站内通知。')
  await admin.getByLabel('接收范围',{exact:true}).selectOption('user')
  await admin.getByLabel('查找用户',{exact:true}).fill('预览社员')
  await admin.getByLabel('接收用户',{exact:true}).selectOption(owner)
  await admin.getByRole('button',{name:'预览通知',exact:true}).click()
  await admin.getByText('1 位接收用户',{exact:true}).waitFor()
  await admin.getByRole('button',{name:'确认发送',exact:true}).click()
  await admin.getByText('已发送至 1 位用户',{exact:true}).waitFor()
  await member.goto(base+'/messages/')
  await member.getByRole('button',{name:'站内通知',exact:true}).click()
  await member.getByRole('link',{name:noticeTitle,exact:true}).waitFor()
  const noticeRow=member.locator('.notification-row').filter({hasText:noticeTitle})
  await noticeRow.getByRole('button',{name:'标记已读',exact:true}).click()
  await noticeRow.getByRole('button',{name:'归档消息',exact:true}).click()
  await member.locator('.message-filters select').selectOption('archived')
  await noticeRow.getByRole('button',{name:'恢复消息',exact:true}).click()
  await member.locator('.message-filters select').selectOption('all')
  await member.getByRole('link',{name:noticeTitle,exact:true}).waitFor()
  await member.screenshot({path:'artifacts/message-inbox-desktop.png',fullPage:true})
  await member.setViewportSize({width:390,height:844});assert.ok(await member.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await member.screenshot({path:'artifacts/message-inbox-mobile.png',fullPage:true})
  await guest.goto(base+'/admin/');await guest.getByRole('alert').filter({hasText:'请先登录'}).waitFor()
  assert.equal(await guest.locator('.admin-sidebar').count(),0)
  assert.deepEqual(errors,[])
  console.log('PASS: admin queue, private permissions, notice preview/send, member read/archive/restore, desktop/mobile layout')
 }finally{await b.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
