const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const {join}=require('node:path')
const base=process.env.RD_UI_TEST_URL||'http://127.0.0.1:5189'
assert.equal(new URL(base).hostname,'127.0.0.1','Upload checks write only to the local fixture')
async function main() {
  const browser=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']})
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}})
    const errors=[];page.on('pageerror',error=>errors.push(error.message))
    await page.goto(base+'/api/__preview/member',{waitUntil:'domcontentloaded'})
    await page.goto(base+'/mcp/',{waitUntil:'domcontentloaded'})
    await page.getByRole('button',{name:'创建令牌',exact:true}).click()
    const field=page.getByRole('textbox',{name:'新上传令牌'})
    await field.waitFor()
    const token=await field.inputValue()
    const upload=async(tool,body)=>{
      const response=await page.request.post(base+'/api/note-upload/'+tool,{headers:{Authorization:'Bearer '+token},data:body})
      assert.ok(response.ok(),await response.text());return response.json()
    }
    const image=await upload('upload_note_image',{base64:readFileSync('docs/public/images/rd-studio-logo.png').toString('base64')})
    const markdown='# V2md 浏览器检查\n\n![截图]('+image.url+')\n\n$E=mc^2$\n\n```js\nconst value = 1\n```\n\n脚注[^note]\n\n[^note]: 保留原文'
    const draft=await upload('save_article_draft',{import_key:'browser-verification',title:'V2md 浏览器检查',markdown,tags:['视频转文']})
    assert.equal(draft.status,'draft')
    const anonymous=await browser.newContext()
    assert.equal((await anonymous.request.get(image.url)).status(),404)
    await anonymous.close()
    await page.goto(draft.editor_url,{waitUntil:'domcontentloaded'})
    await page.waitForFunction(source=>document.querySelector('.content-editor')?.value===source,markdown)
    const picture=page.locator('.preview-body img')
    await picture.scrollIntoViewIfNeeded()
    await page.waitForFunction(()=>document.querySelector('.preview-body img')?.naturalWidth>0)
    assert.equal(await page.locator('.preview-body .katex-error').count(),0)
    assert.equal(await page.locator('.preview-body .footnote-item').count(),1)
    const changed=markdown+'\n\n编辑后的段落'
    await page.locator('.content-editor').fill(changed)
    const saved=page.waitForResponse(r=>r.url().includes('/api/data/articles')&&r.request().method()==='PATCH')
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    assert.ok((await saved).ok())
    const own=await upload('get_own_draft',{id:draft.id})
    assert.equal(own.markdown,changed);assert.equal(own.status,'draft')
    const submitted=page.waitForResponse(r=>r.url().includes('/api/data/articles')&&r.request().method()==='PATCH')
    await page.getByRole('button',{name:'提交审核',exact:true}).click()
    assert.ok((await submitted).ok())
    const row=await (await page.request.get(base+'/api/data/articles?id=eq.'+draft.id)).json()
    assert.equal(row[0].status,'pending')
    await page.goto(base+'/mcp/',{waitUntil:'domcontentloaded'})
    await page.getByRole('button',{name:'撤销',exact:true}).click()
    await page.getByText('令牌已撤销',{exact:true}).waitFor()
    assert.equal((await page.request.post(base+'/api/note-upload/get_upload_identity',{headers:{Authorization:'Bearer '+token},data:{}})).status(),401)
    await page.screenshot({path:join(process.env.TEMP,'rd-note-upload-desktop.png'),fullPage:true})
    await page.setViewportSize({width:390,height:844})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:join(process.env.TEMP,'rd-note-upload-mobile.png'),fullPage:true})
    assert.deepEqual(errors,[])
    console.log('Browser token management, image preview, draft editing, review submission and revocation passed.')
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
