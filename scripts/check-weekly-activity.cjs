const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const base=process.env.RD_UI_TEST_URL||'http://127.0.0.1:5194'
assert.equal(new URL(base).hostname,'127.0.0.1')
async function main(){
 const b=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']})
 try{
  const member=await b.newPage({viewport:{width:1440,height:1000}}),guest=await b.newPage({viewport:{width:1440,height:1000}}),second=await b.newPage()
  const errors=[];for(const p of [member,guest,second])p.on('pageerror',e=>errors.push(e.message))
  let awards=0;member.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/community/checkin'))awards++})
  const checked=member.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/community/checkin'))
  await member.goto(base+'/api/__preview/member')
  const award=await (await checked).json();assert.equal(award.reward,5);assert.equal(award.already,false)
  await member.getByRole('dialog').filter({hasText:'每日签到'}).waitFor()
  assert.equal(await member.locator('.checkin-number').innerText(),'1')
  await member.screenshot({path:'artifacts/automatic-checkin.png'})
  await member.getByRole('button',{name:'完成',exact:true}).click()
  const daily=member.waitForResponse(r=>r.url().endsWith('/community/daily'))
  await member.reload();await daily
  assert.equal(await member.locator('.checkin-dialog[open]').count(),0);assert.equal(awards,1)
  let otherAwards=0;second.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/community/checkin'))otherAwards++})
  const sameDay=second.waitForResponse(r=>r.url().endsWith('/community/daily'))
  await second.goto(base+'/api/__preview/member');await sameDay
  assert.equal(otherAwards,0);assert.equal(await second.locator('.checkin-dialog[open]').count(),0)
  await member.goto(base+'/activity/',{waitUntil:'networkidle'})
  await member.locator('.weekly-own').filter({hasText:'+5 EXP'}).waitFor()
  const current=(await (await guest.request.get(base+'/api/activity/weekly')).json())
  assert.ok(current.total>=1);assert.equal(current.items.find(p=>p.username==='预览社员').weekly_exp,5);assert.equal(current.own,null)
  await guest.goto(base+'/activity/',{waitUntil:'networkidle'})
  await guest.locator('.weekly-list').getByRole('link',{name:'预览社员',exact:true}).waitFor()
  await guest.screenshot({path:'artifacts/weekly-activity-desktop.png',fullPage:true})
  await guest.setViewportSize({width:390,height:844})
  assert.ok(await guest.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await guest.screenshot({path:'artifacts/weekly-activity-mobile.png',fullPage:true})
  await guest.getByRole('button',{name:'上一周',exact:true}).click()
  await guest.locator('.weekly-empty').waitFor()
  await guest.getByRole('button',{name:'回到本周',exact:true}).click()
  await guest.locator('.weekly-list').getByRole('link',{name:'预览社员',exact:true}).waitFor()
  await guest.goto(base+'/',{waitUntil:'networkidle'})
  await guest.locator('.weekly-activity.compact').getByRole('link',{name:'预览社员',exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: automatic first-visit checkin, reload/device deduplication, weekly EXP, public board, week switching, home widget and responsive layout')
 }finally{await b.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
