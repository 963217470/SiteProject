const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const {join}=require('node:path')
const base=process.env.RD_UI_TEST_URL||'http://127.0.0.1:5188'
const source=readFileSync('docs/public/examples/markdown-compatibility.md','utf8')
assert.equal(new URL(base).hostname,'127.0.0.1','This test writes only to the isolated local fixture')

async function checkProse(page,selector) {
  const root=page.locator(selector)
  await root.locator('.katex').first().waitFor()
  assert.equal(await root.locator('.katex-error').count(),0)
  assert.equal(await root.locator('.rd-math').count(),6)
  assert.equal(await root.locator('.footnote-item').count(),2)
  assert.equal(await root.locator('.markdown-alert').count(),2)
  assert.equal(await root.locator('.katex .tag').first().evaluate(el=>getComputedStyle(el).borderTopWidth),'0px')
  assert.equal(await root.locator('.task-list-item-checkbox').first().evaluate(el=>getComputedStyle(el).width),'14px')
  assert.ok((await root.locator('pre code').first().innerText()).includes('```js'))
  assert.ok((await root.locator('h2').allTextContents()).includes('3. 代码之后的标题'))
  const copy=await root.evaluate(el=>{
    const range=document.createRange()
    range.selectNode(el.querySelector('.rd-math'))
    const selection=getSelection();selection.removeAllRanges();selection.addRange(range)
    const data=new DataTransfer()
    el.dispatchEvent(new ClipboardEvent('copy',{clipboardData:data,bubbles:true,cancelable:true}))
    selection.removeAllRanges()
    return data.getData('text/plain')
  })
  assert.equal(copy,'$E = mc^2$')
  assert.equal(await root.evaluate(el=>[...el.querySelectorAll('.table-of-contents a,.footnote-ref a,.rd-equation-ref')].every(a=>document.getElementById(a.getAttribute('href').slice(1)))),true)
  return root
}

async function main() {
  const browser=await chromium.launch({channel:'msedge',headless:true,args:['--disable-gpu']})
  const errors=[]
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}})
    page.setDefaultTimeout(15000)
    page.on('pageerror',error=>errors.push(error.message))
    await page.route('https://rd-studio.club/images/rd-studio-logo.png',route=>route.fulfill({contentType:'image/png',body:readFileSync('docs/public/images/rd-studio-logo.png')}))
    await page.goto(base+'/api/__preview/admin',{waitUntil:'domcontentloaded'})
    await page.goto(base+'/editor/',{waitUntil:'domcontentloaded'})
    await page.locator('.title-field input').fill('Markdown verification')
    await page.locator('.content-editor').fill(source)
    await checkProse(page,'.preview-body')
    await page.getByRole('button',{name:'预览',exact:true}).click()
    await page.getByRole('button',{name:'Markdown',exact:true}).click()
    assert.equal(await page.locator('.content-editor').inputValue(),source)
    const save=page.waitForResponse(response=>response.url().includes('/api/data/articles')&&response.request().method()==='POST')
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    const response=await save
    assert.ok(response.ok(),await response.text())
    const saved=await response.json()
    const id=saved[0].id
    const persisted=await (await page.request.get(base+'/api/data/articles?id=eq.'+id)).json()
    assert.equal(persisted[0].content,source)
    await page.goto(base+'/article?id='+id,{waitUntil:'domcontentloaded'})
    const article=await checkProse(page,'.article-body')
    await article.locator('.rd-math-display').first().scrollIntoViewIfNeeded()
    await page.screenshot({path:join(process.env.TEMP,'rd-markdown-article-desktop.png')})
    await page.setViewportSize({width:390,height:844})
    await article.locator('.markdown-alert').first().scrollIntoViewIfNeeded()
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:join(process.env.TEMP,'rd-markdown-article-mobile.png')})
    await page.setViewportSize({width:1440,height:1000})
    await page.goto(base+'/games-tools/',{waitUntil:'domcontentloaded'})
    await page.getByRole('button',{name:'发布作品',exact:true}).click()
    await page.locator('.catalog-source').fill(source)
    await page.getByRole('button',{name:'预览',exact:true}).click()
    await checkProse(page,'.catalog-prose')
    await page.locator('.catalog-prose .rd-math-display').first().scrollIntoViewIfNeeded()
    await page.screenshot({path:join(process.env.TEMP,'rd-markdown-catalog-desktop.png')})
    await page.setViewportSize({width:390,height:844})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:join(process.env.TEMP,'rd-markdown-catalog-mobile.png')})
    assert.deepEqual(errors,[])
    console.log('PASS: editor original-source persistence, article and catalog syntax, anchors, one-copy TeX, desktop/mobile, no browser exceptions.')
  } finally {await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
